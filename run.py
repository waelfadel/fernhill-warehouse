"""
Fernhill warehouse - one-command build.

    pip install -r requirements.txt
    python run.py

Steps:
  1. Rebuild warehouse.duckdb from scratch (bronze -> silver -> gold)
  2. Run the data quality checks; stop with an error if any fail
  3. Run the four business questions; print them and save them to output/
"""
import os
import pathlib
import sys

import duckdb

ROOT = pathlib.Path(__file__).resolve().parent
os.chdir(ROOT)                      # all SQL uses paths relative to the repo

DB_PATH = ROOT / "warehouse.duckdb"
SQL_DIR = ROOT / "sql"
OUT_DIR = ROOT / "output"
LAYERS = ["01_bronze.sql", "02_silver.sql", "03_gold.sql", "04_checks.sql"]


def table_text(columns, rows):
    """Plain-text table for the console."""
    cells = [[("" if v is None else str(v)) for v in r] for r in rows]
    widths = [max(len(c), *(len(r[i]) for r in cells)) if cells else len(c)
              for i, c in enumerate(columns)]
    line = lambda vals: "  ".join(v.ljust(w) for v, w in zip(vals, widths))
    return "\n".join([line(columns), line(["-" * w for w in widths])] + [line(r) for r in cells])


def table_markdown(columns, rows):
    out = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for r in rows:
        out.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    return "\n".join(out)


def main():
    # 1. Clean rebuild ---------------------------------------------------
    for p in (DB_PATH, DB_PATH.with_suffix(".duckdb.wal")):
        if p.exists():
            p.unlink()
    con = duckdb.connect(str(DB_PATH))
    con.execute("SET TimeZone = 'UTC'")          # same results on every machine

    print("== Building warehouse")
    for name in LAYERS:
        print(f"   running sql/{name}")
        con.execute((SQL_DIR / name).read_text(encoding="utf-8"))

    for schema in ("bronze", "silver", "gold"):
        tables = con.execute(
            "select table_name, estimated_size from duckdb_tables() "
            "where schema_name = ? order by table_name", [schema]).fetchall()
        print(f"   {schema:<6}: " + ", ".join(f"{t} ({n})" for t, n in tables))

    # 2. Data quality ------------------------------------------------------
    print("\n== Data quality checks")
    checks = con.execute(
        "select schema_name, view_name from duckdb_views() "
        "where schema_name in ('dq', 'dq_warn') order by schema_name, view_name").fetchall()
    failures = []
    for schema, view in checks:
        n = con.execute(f'select count(*) from {schema}."{view}"').fetchone()[0]
        if schema == "dq":
            print(f"   {'PASS' if n == 0 else 'FAIL'}  {view}" + ("" if n == 0 else f"  ({n} rows)"))
            if n:
                failures.append(view)
        else:
            cur = con.execute(f'select * from {schema}."{view}"')
            cols = [d[0] for d in cur.description]
            print(f"   WARN  {view}  ({n} rows)")
            print("         " + table_text(cols, cur.fetchall()).replace("\n", "\n         "))

    if failures:
        print("\nBuild FAILED. Inspect a failing check with e.g.:")
        print(f"   select * from dq.{failures[0]};")
        sys.exit(1)

    # 3. Business questions ------------------------------------------------
    OUT_DIR.mkdir(exist_ok=True)
    md = ["# Answers (generated by run.py)\n"]
    for q in sorted((SQL_DIR / "answers").glob("*.sql")):
        sql = q.read_text(encoding="utf-8").strip().rstrip(";")
        cur = con.execute(sql)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        con.execute(f"COPY ({sql}) TO '{(OUT_DIR / (q.stem + '.csv')).as_posix()}' (HEADER)")
        print(f"\n== {q.stem}\n" + table_text(cols, rows))
        md.append(f"## {q.stem}\n\n{table_markdown(cols, rows)}\n")
    (OUT_DIR / "answers.md").write_text("\n".join(md), encoding="utf-8")

    con.close()
    print(f"\nDone. Warehouse: {DB_PATH.name}   Results: output/*.csv, output/answers.md")


if __name__ == "__main__":
    main()
